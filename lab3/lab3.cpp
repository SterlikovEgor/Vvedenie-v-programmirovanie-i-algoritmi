#include <iostream>
#include <iomanip>
#include <cmath>

// Функция для очистки буфера ввода при ошибке или некорректном вводе
void clearInputBuffer() {
    std::cin.clear();
    std::cin.ignore(32767, '\n');
}

//--------------------------------------------------------------------------------------------------
// УРОВЕНЬ 1 (Базовый - Вариант 13)
// Задание: Запросить число. Если оно равно 0, вывести "Ноль", иначе вывести "Не ноль"
//--------------------------------------------------------------------------------------------------
void runTask1() {
    std::cout << "\n==========================================\n";
    std::cout << "[ БАЗОВЫЙ УРОВЕНЬ: Проверка числа на ноль ]\n";
    std::cout << "==========================================\n";

    double number = 0.0;
    std::cout << "Введите число: ";

    while (!(std::cin >> number)) {
        std::cout << "Ошибка! Введите корректное число: ";
        clearInputBuffer();
    }

    // Сравнение вещественного числа с нулем с учетом погрешности (epsilon)
    if (std::fabs(number) < 1e-9) {
        std::cout << "Результат: Ноль\n";
    } else {
        std::cout << "Результат: Не ноль\n";
    }
}

//--------------------------------------------------------------------------------------------------
// УРОВЕНЬ 2 (Средний - Вариант 13)
// Задание: Запросить число от 1 до 7 (день недели). Вывести название дня и рабочий/выходной
//--------------------------------------------------------------------------------------------------
void runTask2() {
    std::cout << "\n==========================================\n";
    std::cout << "[ СРЕДНИЙ УРОВЕНЬ: День недели ]\n";
    std::cout << "==========================================\n";

    int day = 0;
    std::cout << "Введите номер дня недели (1-7): ";

    while (!(std::cin >> day)) {
        std::cout << "Ошибка ввода! Введите целое число от 1 до 7: ";
        clearInputBuffer();
    }

    // Проверка диапазона [1, 7]
    if (day < 1 || day > 7) {
        std::cout << "Ошибка: Номер дня недели должен быть в диапазоне от 1 до 7!\n";
        return;
    }

    // Определение названия дня и типа дня (рабочий / выходной)
    if (day == 1) {
        std::cout << "День недели: Понедельник (Рабочий день)\n";
    } else if (day == 2) {
        std::cout << "День недели: Вторник (Рабочий день)\n";
    } else if (day == 3) {
        std::cout << "День недели: Среда (Рабочий день)\n";
    } else if (day == 4) {
        std::cout << "День недели: Четверг (Рабочий день)\n";
    } else if (day == 5) {
        std::cout << "День недели: Пятница (Рабочий день)\n";
    } else if (day == 6) {
        std::cout << "День недели: Суббота (Выходной день)\n";
    } else if (day == 7) {
        std::cout << "День недели: Воскресенье (Выходной день)\n";
    }
}

//--------------------------------------------------------------------------------------------------
// УРОВЕНЬ 3 (Повышенный - Вариант 13)
// Задание: Калькулятор доставки (расстояние, вес, срочность). Проверка положительности
//--------------------------------------------------------------------------------------------------
void runTask3() {
    std::cout << "\n==========================================\n";
    std::cout << "[ ПОВЫШЕННЫЙ УРОВЕНЬ: Калькулятор доставки ]\n";
    std::cout << "==========================================\n";

    double distance = 0.0;
    double weight = 0.0;
    int urgencyChoice = 0;

    // Ввод расстояния
    std::cout << "Введите расстояние доставки (км): ";
    while (!(std::cin >> distance) || distance <= 0.0) {
        std::cout << "Ошибка! Расстояние должно быть положительным числом (> 0). Повторите ввод: ";
        clearInputBuffer();
    }

    // Ввод веса
    std::cout << "Введите вес груза (кг): ";
    while (!(std::cin >> weight) || weight <= 0.0) {
        std::cout << "Ошибка! Вес груза должен быть положительным числом (> 0). Повторите ввод: ";
        clearInputBuffer();
    }

    // Ввод срочности
    std::cout << "Выберите тип доставки (1 — Обычная, 2 — Быстрая [+50% к стоимости]): ";
    while (!(std::cin >> urgencyChoice) || (urgencyChoice != 1 && urgencyChoice != 2)) {
        std::cout << "Ошибка! Введите 1 (Обычная) или 2 (Быстрая): ";
        clearInputBuffer();
    }

    // Базовая стоимость: 50 руб + 10 руб/км + 20 руб/кг
    const double BASE_FEE = 50.0;
    const double PER_KM_FEE = 10.0;
    const double PER_KG_FEE = 20.0;

    double totalCost = BASE_FEE + (distance * PER_KM_FEE) + (weight * PER_KG_FEE);

    if (urgencyChoice == 2) {
        totalCost *= 1.5; // Наценка 50% за срочность
    }

    std::cout << std::fixed << std::setprecision(2);
    std::cout << "\n--- Детализация расчета ---\n";
    std::cout << "Расстояние: " << distance << " км\n";
    std::cout << "Вес: " << weight << " кг\n";
    std::cout << "Тип доставки: " << (urgencyChoice == 2 ? "Быстрая (+50%)" : "Обычная") << "\n";
    std::cout << "Итоговая стоимость доставки: " << totalCost << " руб.\n";
}

//--------------------------------------------------------------------------------------------------
// Главная функция с консольным меню
//--------------------------------------------------------------------------------------------------
int main() {
    setlocale(LC_ALL, "ru");

    int choice = 0;
    do {
        std::cout << "\n==========================================\n";
        std::cout << "   ЛАБОРАТОРНАЯ РАБОТА №3 (ВАРИАНТ 13)\n";
        std::cout << "==========================================\n";
        std::cout << "1 — Базовый уровень (Проверка на ноль)\n";
        std::cout << "2 — Средний уровень (День недели)\n";
        std::cout << "3 — Повышенный уровень (Калькулятор доставки)\n";
        std::cout << "4 — Выполнить ВСЕ уровни подряд\n";
        std::cout << "0 — Выход\n";
        std::cout << "Выберите действие (0-4): ";

        if (!(std::cin >> choice)) {
            clearInputBuffer();
            choice = -1;
            continue;
        }

        switch (choice) {
            case 1:
                runTask1();
                break;
            case 2:
                runTask2();
                break;
            case 3:
                runTask3();
                break;
            case 4:
                runTask1();
                runTask2();
                runTask3();
                break;
            case 0:
                std::cout << "\nЗавершение работы программы.\n";
                break;
            default:
                std::cout << "\nНекорректный выбор! Введите число от 0 до 4.\n";
                break;
        }
    } while (choice != 0);

    return 0;
}