#include <iostream>
#include <iomanip>
#include <cmath>

// Функция для очистки буфера ввода при ошибке (например, если вместо числа ввели букву)
void clearInputBuffer() {
    std::cin.clear();
    std::cin.ignore(32767, '\n');
}
//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// УРОВЕНЬ 1 (Базовый - Вариант 13)
// Задание: Вычислить разность двух чисел a - b

void runTask1() {
    std::cout << "\n==========================================\n";
    std::cout << "[ БАЗОВЫЙ УРОВЕНЬ: Разность двух чисел (a - b) ]\n";
    std::cout << "==========================================\n";

    double a = 0.0, b = 0.0; // Тип double для универсальности ввода целых и дробных чисел

    std::cout << "Введите уменьшаемое (a): ";
    while (!(std::cin >> a)) {
        std::cout << "Ошибка ввода! Введите число для a: ";
        clearInputBuffer();
    }

    std::cout << "Введите вычитаемое (b): ";
    while (!(std::cin >> b)) {
        std::cout << "Ошибка ввода! Введите число для b: ";
        clearInputBuffer();
    }

    double difference = a - b;
    std::cout << std::fixed << std::setprecision(2);
    std::cout << "Результат: " << a << " - " << b << " = " << difference << "\n";
}

//------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
// УРОВЕНЬ 2 (Средний - Вариант 13)
// Задание: Вычислить расстояние по скорости и времени (S = v * t)

void runTask2() {
    std::cout << "\n==========================================\n";
    std::cout << "[ СРЕДНИЙ УРОВЕНЬ: Расстояние по скорости и времени ]\n";
    std::cout << "==========================================\n";

    double speed = 0.0;
    double time = 0.0;

    std::cout << "Введите скорость (км/ч): ";
    while (!(std::cin >> speed) || speed < 0) {
        std::cout << "Ошибка! Скорость не может быть отрицательной. Повторите ввод: ";
        clearInputBuffer();
    }

    std::cout << "Введите время (ч): ";
    while (!(std::cin >> time) || time < 0) {
        std::cout << "Ошибка! Время не может быть отрицательным. Повторите ввод: ";
        clearInputBuffer();
    }

    // Вычисление с явным приведением типов static_cast
    double distance = static_cast<double>(speed) * time;
    std::cout << std::fixed << std::setprecision(2);
    std::cout << "Пройденное расстояние: " << distance << " км\n";
}

