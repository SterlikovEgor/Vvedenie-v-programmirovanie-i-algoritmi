// УРОВЕНЬ 3 (Повышенный - Вариант 13)
// Задание: Вычислить выражение y = (a + b) / (c - d) с проверкой деления на ноль

void runTask3() {
    std::cout << "\n==========================================\n";
    std::cout << "[ ПОВЫШЕННЫЙ УРОВЕНЬ: Выражение y = (a + b) / (c - d) ]\n";
    std::cout << "==========================================\n";

    double varA = 0.0, varB = 0.0, varC = 0.0, varD = 0.0;

    std::cout << "Введите значение a: ";
    while (!(std::cin >> varA)) { clearInputBuffer(); std::cout << "Ошибка ввода! Повторите ввод a: "; }

    std::cout << "Введите значение b: ";
    while (!(std::cin >> varB)) { clearInputBuffer(); std::cout << "Ошибка ввода! Повторите ввод b: "; }

    std::cout << "Введите значение c: ";
    while (!(std::cin >> varC)) { clearInputBuffer(); std::cout << "Ошибка ввода! Повторите ввод c: "; }

    std::cout << "Введите значение d: ";
    while (!(std::cin >> varD)) { clearInputBuffer(); std::cout << "Ошибка ввода! Повторите ввод d: "; }

    // Проверка деления на ноль
    double denominator = varC - varD;
    if (std::abs(denominator) < 1e-9) {
        std::cout << "КРИТИЧЕСКАЯ ОШИБКА: Деление на ноль! Знаменатель (c - d) равен 0.\n";
    } else {
        double numerator = static_cast<double>(varA) + varB;
        double resultY = numerator / denominator;

        std::cout << std::fixed << std::setprecision(4);
        std::cout << "Результат вычисления выражения y = " << resultY << "\n";

        // Демонстрация усечения vs округления
        int truncated = static_cast<int>(resultY);
        int rounded = static_cast<int>(std::round(resultY));
        std::cout << "  Усечение (static_cast<int>): " << truncated << "\n";
        std::cout << "  Округление (std::round):     " << rounded << "\n";
    }
}

