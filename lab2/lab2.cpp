// Главная функция программы
int main() {
    setlocale(LC_ALL, "ru");

    int choice = 0;
    do {
        std::cout << "\n==========================================\n";
        std::cout << "   ЛАБОРАТОРНАЯ РАБОТА №2 (ВАРИАНТ 13)\n";
        std::cout << "==========================================\n";
        std::cout << "1 — Выполнить Базовый уровень\n";
        std::cout << "2 — Выполнить Средний уровень\n";
        std::cout << "3 — Выполнить Повышенный уровень\n";
        std::cout << "4 — Выполнить ВСЕ уровни подряд\n";
        std::cout << "0 — Выход\n";
        std::cout << "Выберите действие (0-4): ";

        if (!(std::cin >> choice)) {
            clearInputBuffer();
            choice = -1;
            continue;
        }

        switch (choice) {
            case 1:
                runTask1();
                break;
            case 2:
                runTask2();
                break;
            case 3:
                runTask3();
                break;
            case 4:
                runTask1();
                runTask2();
                runTask3();
                break;
            case 0:
                std::cout << "\nЗавершение работы программы.\n";
                break;
            default:
                std::cout << "\nНекорректный выбор! Введите число от 0 до 4.\n";
                break;
        }
    } while (choice != 0);

    return 0;
}

